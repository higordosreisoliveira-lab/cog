/** 1 → 1st, 2 → 2nd, 3 → 3rd, 11 → 11th, 22 → 22nd… */
const ordinal = (n: number) => {
  const tens = n % 100;
  const suffix = tens >= 11 && tens <= 13 ? 'th' : ['th', 'st', 'nd', 'rd'][n % 10] ?? 'th';
  return `${n}${suffix}`;
};

